using System.Drawing;

namespace CodexQuota.Tray;

/// <summary>Portable rules for the always-custom hover presentation.</summary>
internal static class TrayHoverPolicy
{
    public const int NativeTextLimit = 127;
    public static bool RequiresPopup(string text) => text.Length > 0;

    // Empty, rather than truncated, also suppresses the legacy Shell tooltip if
    // Explorer rejects NOTIFYICON_VERSION_4 and therefore ignores NIF_SHOWTIP.
    public static string NativeText(string text) => RequiresPopup(text) ? "" : text;
    public static string[] Lines(string text) => text.Replace("\r\n", "\n").Replace('\r', '\n').Split('\n');

    public static Rectangle Place(Rectangle icon, Rectangle workArea, int width, int contentHeight, int padding)
    {
        var height = (int)Math.Min(int.MaxValue, Math.Max(1L, (long)contentHeight + 2L * padding));
        return TrayMenuPlacement.Calculate(icon, workArea, new Size(width, height));
    }
}

/// <summary>
/// Escape/click/menu dismissal stays suppressed until the pointer leaves. A short
/// crossing grace permits moving across taskbar padding from the icon to the popup.
/// This is observed only by the existing hover timer, never an idle/global hook.
/// </summary>
internal sealed class TrayHoverSession
{
    public const int CrossingGraceMilliseconds = 200;
    private long? _outsideSince;
    public bool Suppressed { get; private set; }
    public bool ShellOwnsLifetime { get; private set; }
    public void Reset() { Suppressed = false; ShellOwnsLifetime = false; _outsideSince = null; }
    public void Suppress() { Suppressed = true; ShellOwnsLifetime = false; _outsideSince = null; }

    public void Open(bool fromShell, bool pointerOverIcon)
    {
        // NIN_POPUPOPEN may be generated by keyboard selection. The unrelated
        // pointer cannot determine that session's lifetime; POPUPCLOSE does.
        ShellOwnsLifetime = fromShell && !pointerOverIcon;
        _outsideSince = null;
    }

    public bool CloseFromShell(bool pointerOverPopup = false)
    {
        if (pointerOverPopup && ShellOwnsLifetime && !Suppressed)
        {
            ShellOwnsLifetime = false; // Mouse takes over a keyboard-opened scrollable card.
            _outsideSince = null;
            return false;
        }
        if (!ShellOwnsLifetime) return false; // Pointer may be crossing into the scrollable popup.
        Reset();
        return true;
    }

    public bool ObservePointer(bool overIcon, bool overPopup, bool popupVisible, long milliseconds)
    {
        if (popupVisible && overPopup && !Suppressed) ShellOwnsLifetime = false;
        if (ShellOwnsLifetime && !Suppressed) return true;
        if (overIcon || (popupVisible && overPopup))
        {
            _outsideSince = null;
            return true;
        }
        if (popupVisible && !Suppressed)
        {
            _outsideSince ??= milliseconds;
            if (milliseconds - _outsideSince.Value < CrossingGraceMilliseconds) return true;
        }
        Reset();
        return false;
    }
}
